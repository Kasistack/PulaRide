// ---- Retrofit API ---------------------------------------------------------

interface SupabaseApi {
    @POST("/auth/v1/signup")
    suspend fun signInAnonymous(@Body body: AuthAnonymousRequest): Response<AuthSession>

    @GET("/auth/v1/user")
    suspend fun getUser(@Header("Authorization") bearer: String): Response<AuthUser>

    @GET("/rest/v1/drivers")
    suspend fun getAvailableDrivers(
        @Header("Authorization") bearer: String,
        @Query("available", encoded = true) available: String = "eq.true",
        @Query("select", encoded = true) select: String = "*",
        @Query("order", encoded = true) order: String = "last_updated.desc"
    ): Response<List<DriverRow>>

    @POST("/rest/v1/drivers")
    suspend fun upsertDriver(
        @Header("Authorization") bearer: String,
        @Header("Prefer") prefer: String = "resolution=merge-duplicates,return=minimal",
        @Body body: DriverUpsert
    ): Response<Unit>

    @POST("/rest/v1/ride_requests")
    suspend fun createRideRequest(
        @Header("Authorization") bearer: String,
        @Header("Prefer") prefer: String = "return=representation",
        @Body body: RideRequestInsert
    ): Response<List<RideRequestRow>>

    @GET("/rest/v1/bids")
    suspend fun getBids(
        @Header("Authorization") bearer: String,
        @Query("request_id", encoded = true) requestId: String,
        @Query("select", encoded = true) select: String = "*",
        @Query("order", encoded = true) order: String = "created_at.asc"
    ): Response<List<BidRow>>

    @POST("/rest/v1/bids")
    suspend fun createBid(
        @Header("Authorization") bearer: String,
        @Header("Prefer") prefer: String = "return=minimal",
        @Body body: BidInsert
    ): Response<Unit>

    @GET("/rest/v1/messages")
    suspend fun getMessages(
        @Header("Authorization") bearer: String,
        @Query("ride_id", encoded = true) rideId: String,
        @Query("select", encoded = true) select: String = "*",
        @Query("order", encoded = true) order: String = "created_at.asc"
    ): Response<List<MessageRow>>

    @POST("/rest/v1/messages")
    suspend fun sendMessage(
        @Header("Authorization") bearer: String,
        @Header("Prefer") prefer: String = "return=minimal",
        @Body body: MessageInsert
    ): Response<Unit>

    // Wallet balance (owned by caller; RLS enforces owner-only read).
    @GET("/rest/v1/wallets")
    suspend fun getWallet(
        @Header("Authorization") bearer: String,
        @Query("select", encoded = true) select: String = "balance",
        @Query("limit", encoded = true) limit: Int = 1
    ): Response<List<WalletRow>>
}

@JsonClass(generateAdapter = true)
data class WalletRow(
    val balance: Double? = null
)

// ---- Ride creation (server-validated; no direct client INSERT) ------------

interface RideFunctionApi {
    @Headers("Content-Type: application/json")
    @POST("functions/v1/create-ride")
    suspend fun createRide(
        @Body body: CreateRideRequest
    ): Response<CreateRideResponse>
}

@JsonClass(generateAdapter = true)
data class CreateRideRequest(
    val requestId: String,
    val bidId: String
)

@JsonClass(generateAdapter = true)
data class CreateRideResponse(
    val ride: RideCreatedRow? = null,
    val error: String? = null
)

object RideFunctionClient {
    private val moshi = com.squareup.moshi.Moshi.Builder()
        .add(com.squareup.moshi.kotlin.reflect.KotlinJsonAdapterFactory())
        .build()

    val api: RideFunctionApi by lazy {
        retrofit2.Retrofit.Builder()
            .baseUrl("${SupabaseConfig.url}/")
            .addConverterFactory(
                retrofit2.converter.moshi.MoshiConverterFactory.create(moshi)
            )
            .client(
                okhttp3.OkHttpClient.Builder()
                    .addInterceptor(okhttp3.Interceptor { chain ->
                        chain.proceed(
                            chain.request().newBuilder()
                                .addHeader("apikey", SupabaseConfig.anonKey)
                                .addHeader("Authorization", SupabaseClient.authHeader().let {
                                    if (it.startsWith("Bearer ")) it else "Bearer $it"
                                })
                                .build()
                        )
                    })
                    .build()
            )
            .build()
            .create(RideFunctionApi::class.java)
    }
}

// ---- Auth token holder + client ------------------------------------------

object SupabaseClient {
    var accessToken: String? = null
        private set

    fun setSession(token: String?) {
        accessToken = token
    }

    fun authHeader(): String = "Bearer ${accessToken ?: SupabaseConfig.anonKey}"

    private val moshi = Moshi.Builder().add(KotlinJsonAdapterFactory()).build()

    private val client = OkHttpClient.Builder()
        .connectTimeout(20, TimeUnit.SECONDS)
        .readTimeout(20, TimeUnit.SECONDS)
        .addInterceptor(Interceptor { chain ->
            val req = chain.request().newBuilder()
                .addHeader("apikey", SupabaseConfig.anonKey)
                .build()
            chain.proceed(req)
        })
        .build()

    val api: SupabaseApi by lazy {
        Retrofit.Builder()
            .baseUrl("${SupabaseConfig.url}/")
            .client(client)
            .addConverterFactory(MoshiConverterFactory.create(moshi))
            .build()
            .create(SupabaseApi::class.java)
    }
}
